require "yaml"
require "json"
require "date"

root = File.expand_path("../pseudo", __dir__)
check = ARGV.delete("--check")
abort "Usage: ruby scripts/build_pseudo_games.rb [--check]" unless ARGV.empty?
counts = Hash.new(0)
(2022..2024).each do |year|
  input = YAML.safe_load_file(File.join(root, "hbl_#{year}.yml"))
  definitions = input.fetch("records")
  games = definitions.select { |record| record.fetch("type") == "Game" }.to_h { |record| [record.fetch("code"), record] }
  activations = definitions.select { |record| record.fetch("type") == "Activation" }.group_by { |record| record.fetch("references").fetch("campaign") }
  entries = definitions.select { |record| record.fetch("type") == "Contestant" && games.key?(record.fetch("references").fetch("contest")) }
  records = []
  entries.each do |entry|
    refs = entry.fetch("references")
    game = games.fetch(refs.fetch("contest"))
    game_code = game.fetch("code")
    date = game.fetch("attributes").fetch("begin_date")
    campaign = refs.fetch("campaign")
    roster_code = "#{entry.fetch('code')}-ROSTER"
    roster = activations.fetch(campaign)
    rotation = (Date.iso8601(date) - Date.new(year, 2, 5)).to_i / 7
    ordered = roster.rotate(rotation % roster.length)
    records << { "type" => "Roster", "code" => roster_code,
      "attributes" => { "kind" => "game_availability", "coverage" => "complete", "effective_on" => date,
        "details" => { "game_code" => game_code, "contestant_code" => entry.fetch("code"), "coverage_scope" => "all_12_contracted_players" } },
      "references" => { "campaign" => campaign } }
    weights = [7, 6, 5, 4, 4, 3, 2, 2, 1]
    team_points = entry.fetch("attributes").fetch("tiebreakers").fetch("score")
    points = weights.map { |weight| team_points * weight / weights.sum }
    (team_points - points.sum).times { |index| points[index] += 1 }
    minutes = [34, 34, 34, 34, 34, 22, 18, 16, 14]
    ordered.each_with_index do |activation, index|
      player = activation.fetch("references").fetch("player")
      slot = activation.fetch("code").split("-").last
      stint = "#{campaign}-STINT-#{slot}"
      number = format("%02d", slot.to_i)
      status = index < 10 ? "active" : "inactive"
      reason = { 9 => "coach_decision", 10 => "ankle_soreness", 11 => "rest" }[index]
      details = { "participation" => index < 9 ? "played" : "did_not_play" }
      details["reason"] = reason if reason
      records << { "type" => "RosterEntry", "code" => "#{roster_code}-PLAYER-#{slot}",
        "attributes" => { "status" => status, "jersey_number" => number, "details" => details },
        "references" => { "roster" => roster_code, "player" => player, "stint" => stint } }
      next unless index < 9

      score = points.fetch(index)
      threes = score / 6
      remaining = score - threes * 3
      free_throws = remaining % 2 + (remaining >= 4 ? 2 : 0)
      twos = (remaining - free_throws) / 2
      three_attempts = threes + 1 + index % 2
      two_attempts = twos + 2 + index % 3
      statistics = { "minutes" => minutes.fetch(index), "points" => score,
        "field_goals_made" => twos + threes, "field_goals_attempted" => two_attempts + three_attempts,
        "three_pointers_made" => threes, "three_pointers_attempted" => three_attempts,
        "free_throws_made" => free_throws, "free_throws_attempted" => free_throws + index % 2,
        "rebounds" => (rotation + index * 3) % 10, "assists" => (rotation + index * 2) % 8,
        "steals" => index % 3, "blocks" => (index + 1) % 3, "turnovers" => index % 4, "personal_fouls" => 1 + index % 4 }
      records << { "type" => "Appearance", "code" => "#{entry.fetch('code')}-APPEARANCE-#{slot}",
        "attributes" => { "starter" => index < 5, "jersey_number" => number, "statistics" => statistics },
        "references" => { "player" => player, "contestant" => entry.fetch("code"), "stint" => stint } }
    end
  end
  document = { "format" => "micharisma-seeds/v1", "namespace" => "MIC", "catalog" => "ALA",
    "source" => { "note" => "Fictional complete basketball box scores and availability observations generated by scripts/build_pseudo_games.rb. Availability does not change contracts or stints." },
    "records" => records }
  path = File.join(root, "hbl_#{year}_participation.yml")
  contents = YAML.dump(document)
  if check
    abort "Generated file differs: #{path}" unless File.file?(path) && File.read(path) == contents
  else
    File.write(path, contents)
  end
  records.each { |record| counts[record.fetch("type")] += 1 }
end
puts JSON.pretty_generate(counts.sort.to_h)
